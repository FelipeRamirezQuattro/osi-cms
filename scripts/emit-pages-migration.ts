/**
 * Generates supabase/migrations/0059_pages_reimport_drafts.sql from the same mapper the dry-run uses
 * (QA entregables 5/6, P3). Asset URLs are rewritten to the media-library URLs that
 * scripts/import-page-assets.ts creates.
 *
 * Usage: pnpm exec tsx --env-file=.env.local scripts/emit-pages-migration.ts
 * Inputs: docs/qa/pages-live-state.json (block count + newest updated_at of each page's draft when the dry-run
 *         was reviewed; a page edited since is skipped, never overwritten).
 */
import fs from "node:fs";
import path from "node:path";
import { publicAssetUrl } from "../lib/legacy/asset-path";
import { WIX_PAGE_SPECS, mapWixPage } from "../lib/legacy/map-wix-pages";
import { validateBlockList } from "../lib/validation/blocks";
import { loadItems } from "./plan-wix-pages";

const ROOT = path.join(import.meta.dirname, "..");
const TABLE = "page_blocks_backup_20261102";
const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
if (!supabaseUrl) throw new Error("NEXT_PUBLIC_SUPABASE_URL is not set (run with --env-file=.env.local)");
const live = JSON.parse(fs.readFileSync(path.join(ROOT, "docs/qa/pages-live-state.json"), "utf8")) as Record<string, { n: number; maxupd: string; types?: string }>;

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const json = (v: unknown) => `$json$${JSON.stringify(v)}$json$::jsonb`;

const assetUrls = new Set<string>();
const blocksSql: string[] = [];
for (const spec of WIX_PAGE_SPECS) {
  const mapped = mapWixPage(spec, loadItems(spec.file), {
    assetUrl: (url) => {
      const out = publicAssetUrl(supabaseUrl, url);
      assetUrls.add(out);
      return out;
    },
  });
  const problem = validateBlockList(mapped.blocks.map((b) => ({ type: b.type, data: b.data })));
  if (problem) throw new Error(`${spec.slug}: ${problem.message}`);
  const state = live[spec.slug];
  if (!state) throw new Error(`no live state for ${spec.slug}`);
  const append = mapped.mode === "append";
  const rows = mapped.blocks.map((b, i) => `    (pid, ${q(b.type)}, ${append ? "base + " + (i + 1) * 10 : (i + 1) * 10}, true, ${json(b.data)})`).join(",\n");
  blocksSql.push(`-- ${spec.slug} (${append ? "append after the existing blocks" : "replace the draft blocks"})
do $mig$
declare pid uuid;${append ? "\n  base int;" : ""}
begin
  select id into pid from public.pages where slug = ${q(spec.slug)} and locale = 'en';
  if pid is null then raise exception 'page ${spec.slug} does not exist'; end if;
  if exists (select 1 from public.${TABLE} where page_id = pid) then raise notice 'skipped ${spec.slug}: already applied'; return; end if;
  if not (select count(*) = ${state.n} and coalesce(max(updated_at) = ${q(state.maxupd)}::timestamptz, false) from public.page_blocks where page_id = pid) then
    raise notice 'skipped ${spec.slug}: its draft changed since the dry-run was reviewed'; return;
  end if;${state.types ? `\n  if (select string_agg(type, ',' order by position) from public.page_blocks where page_id = pid) <> ${q(state.types)} then raise notice 'skipped ${spec.slug}: unexpected existing blocks'; return; end if;` : ""}
  insert into public.${TABLE} select b.*, now() from public.page_blocks b where b.page_id = pid;${append ? "\n  select max(position) into base from public.page_blocks where page_id = pid;" : "\n  delete from public.page_blocks where page_id = pid;"}
  insert into public.page_blocks (page_id, type, position, is_visible, data) values
${rows};
  update public.pages set draft_version = draft_version + 1, updated_at = now() where id = pid;
end
$mig$;
`);
}

const header = `-- 0059: re-import of 12 flattened Wix pages as DRAFTS (QA entregables 5/6, P3). GENERATED by scripts/emit-pages-migration.ts.
--
-- What it does
--   * creates ${TABLE} (a copy of page_blocks + backed_up_at) and copies each page's current draft blocks into it
--     BEFORE touching them;
--   * replaces the draft blocks (page_blocks) of 11 pages and APPENDS the distributor/staff directory to /contact
--     (its 4 existing blocks stay);
--   * bumps pages.draft_version so an editor open on a stale copy gets the "changed elsewhere" warning;
--   * adds 5 redirects (/osi-at-pbalf, /gas-release-system-bypass, 3 x /profile/...), nothing else in redirects changes.
-- What it does NOT do
--   * never touches page_publications (the live snapshot), pages.status, SEO fields, any other page, or any redirect
--     that already exists. The live site only changes when someone publishes a page from the admin.
-- Safety
--   * aborts if any imported image/PDF is missing from media_assets -> run \`pnpm import:page-assets\` first;
--   * a page is skipped (with a NOTICE) if its draft changed since the dry-run, or was already migrated by this file;
--   * re-running is a no-op.
--
-- Before applying: pnpm backup:export, then pnpm import:page-assets.
--
-- ROLLBACK (one page; replace the slug) — restores the draft exactly as it was:
--   do $rb$
--   declare pid uuid := (select id from public.pages where slug = 'SLUG' and locale = 'en');
--   begin
--     delete from public.page_blocks where page_id = pid;
--     insert into public.page_blocks select id, page_id, type, position, is_visible, data, created_at, updated_at
--       from public.${TABLE} where page_id = pid;
--     delete from public.${TABLE} where page_id = pid;   -- lets the migration be re-applied later
--     update public.pages set draft_version = draft_version + 1, updated_at = now() where id = pid;
--   end $rb$;
-- All pages at once: run it in a loop over  select distinct page_id from public.${TABLE}.
-- Redirects: delete from public.redirects where from_path in ('/osi-at-pbalf','/gas-release-system-bypass','/profile/ggonzales/profile','/profile/sdowlen/profile','/profile/jramirez95283/profile');
-- Uploaded files (media_assets / Storage folder legacy-pages/) are harmless to keep; remove from /admin/media if wanted.

create table if not exists public.${TABLE} (like public.page_blocks including defaults, backed_up_at timestamptz not null default now());
create index if not exists ${TABLE}_page_idx on public.${TABLE} (page_id);
alter table public.${TABLE} enable row level security;
do $pol$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = '${TABLE}') then
    create policy "staff read ${TABLE}" on public.${TABLE} for select using (public.is_staff());
  end if;
end $pol$;

-- Every imported asset must already be in the media library.
do $assets$
declare missing text;
begin
  select string_agg(u, E'\\n') into missing from unnest(array[
${[...assetUrls].sort().map((u) => `    ${q(u)}`).join(",\n")}
  ]) as u where not exists (select 1 from public.media_assets m where m.url = u);
  if missing is not null then raise exception E'Run "pnpm import:page-assets" first. Missing from media_assets:\\n%', missing; end if;
end
$assets$;

`;

const redirects = `-- Redirects (301, stored by reference where there is something to reference; pending OSI confirmation).
insert into public.redirects (from_path, to_path, target_product_id, status_code, note)
select v.from_path, v.to_path, p.id, 301, 'Pending OSI confirmation'
from (values
  ('/osi-at-pbalf', '/news', null),
  ('/gas-release-system-bypass', null, 'gas-release-system'),
  ('/profile/ggonzales/profile', '/about-us', null),
  ('/profile/sdowlen/profile', '/about-us', null),
  ('/profile/jramirez95283/profile', '/about-us', null)
) as v (from_path, to_path, product_slug)
left join public.products p on p.slug = v.product_slug and p.locale = 'en'
on conflict (from_path) do nothing;

do $$
declare unresolved text;
begin
  select string_agg(from_path, ', ') into unresolved from public.redirects
  where from_path in ('/osi-at-pbalf','/gas-release-system-bypass','/profile/ggonzales/profile','/profile/sdowlen/profile','/profile/jramirez95283/profile')
    and num_nonnulls(to_path, target_product_id, target_page_id) = 0;
  if unresolved is not null then raise exception 'Redirect targets did not resolve for: %', unresolved; end if;
end $$;
`;

const out = path.join(ROOT, "supabase/migrations/0059_pages_reimport_drafts.sql");
fs.writeFileSync(out, header + blocksSql.join("\n") + "\n" + redirects);
console.log(`wrote ${path.relative(ROOT, out)} — ${assetUrls.size} assets, ${WIX_PAGE_SPECS.length} pages`);
