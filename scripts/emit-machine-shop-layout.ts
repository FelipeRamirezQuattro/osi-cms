/**
 * Emits supabase/migrations/0064_machine_shop_layout.sql (QA Entregable 7): the Machine Shop draft's 5 stacked
 * sections become text-beside-photos rows (columns / media_text blocks). Reads the CURRENT draft from the database,
 * reuses its text, image URLs and alt text verbatim, validates the result against the block schemas and writes
 * the migration (draft only, with a backup table, guarded on the draft being unchanged since this run).
 * Read-only against the database. Usage: pnpm exec tsx --env-file=.env.local scripts/emit-machine-shop-layout.ts
 */
import fs from "node:fs";
import path from "node:path";
import { createServiceRoleDbClient } from "../lib/db/client";
import { validateBlockList } from "../lib/validation/blocks";

type Node = { type: string; text?: string; content?: Node[] };
const plain = (n: Node): string => (n.text ?? "") + (n.content ?? []).map(plain).join("");

async function main() {
  const db = createServiceRoleDbClient();
  const { data: page } = await db.from("pages").select("id").eq("slug", "services/machine-shop").eq("locale", "en").single();
  if (!page) throw new Error("services/machine-shop not found");
  const { data: rows } = await db.from("page_blocks").select("*").eq("page_id", page.id).order("position");
  const blocks = rows!;
  if (blocks.length !== 14) throw new Error(`expected 14 draft blocks, found ${blocks.length}`);
  const stamp = blocks.map((b) => b.updated_at).sort().at(-1)!;
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const d = (i: number) => blocks[i].data as Record<string, any>;
  const nodes = (i: number) => (d(i).content.content as Node[]);
  const sectionOf = (headIdx: number, galleryIdx: number) => {
    const [h, ...rest] = nodes(headIdx);
    return {
      type: "columns",
      is_visible: true,
      data: {
        background: "cream",
        spacingTop: "md",
        spacingBottom: "sm",
        columns: [
          { type: "text", heading: plain(h), body: rest.map(plain).join("\n\n") },
          ...(d(galleryIdx).images as { url: string; alt: string }[]).map((im) => ({ type: "image", imageUrl: im.url, imageAlt: im.alt })),
        ],
      },
    };
  };
  const mediaText = (headIdx: number, imageIdx: number, textIdx: number, layout: string) => ({
    type: "media_text",
    is_visible: true,
    data: {
      background: "cream",
      spacingTop: "md",
      spacingBottom: "md",
      mediaType: "image",
      layout,
      title: plain(nodes(headIdx)[0]),
      imageUrl: d(imageIdx).imageUrl,
      imageAlt: d(imageIdx).alt,
      body: nodes(textIdx).map(plain).join("\n\n"),
    },
  });
  const keep = (i: number, over: Record<string, unknown> = {}) => ({ type: blocks[i].type, is_visible: blocks[i].is_visible, data: { ...d(i), ...over } });

  const next = [
    keep(0),
    keep(1),
    sectionOf(2, 3),
    { ...sectionOf(4, 5), data: { ...sectionOf(4, 5).data, spacingTop: "sm" } },
    keep(6, { spacingTop: "sm", spacingBottom: "md" }),
    keep(7),
    mediaText(8, 9, 10, "media-left"),
    mediaText(11, 12, 13, "media-right"),
  ];
  const problem = validateBlockList(next.map((b) => ({ type: b.type, data: b.data })));
  if (problem) throw new Error("schema: " + problem.message);
  fs.mkdirSync("docs/qa", { recursive: true });
  fs.writeFileSync("docs/qa/machine-shop-new-blocks.json", JSON.stringify(next, null, 2));

  const values = next
    .map((b, i) => `    (pid, '${b.type}', ${i}, ${b.is_visible}, $j$${JSON.stringify(b.data)}$j$::jsonb)`)
    .join(",\n");
  const sql = `-- 0064: Machine Shop draft — text beside its photos (QA Entregable 7, design). GENERATED by scripts/emit-machine-shop-layout.ts.
--
-- The 5 stacked sections (heading+text above a full-width gallery/image) become rows: text next to its two photos
-- (Plasma cutting machine, Turning centers) and a photo beside its text (Vertical machining centers, Welding robots).
-- Text, image URLs and alt text are reused verbatim from the current draft; only the block types change
-- (rich_text + image_gallery/image -> columns / media_text). Phones keep the stacked order.
-- Draft only: page_publications / pages.status are not touched, so the live page changes when someone clicks
-- "Publish changes" in the admin. Backup: page_blocks_backup_20261105 (a copy of the 14 current blocks).
-- Guarded: skipped (with a NOTICE) if the draft changed after this file was generated or was already converted. Re-running is a no-op.
--
-- ROLLBACK:
--   do $rb$
--   declare pid uuid := (select id from public.pages where slug = 'services/machine-shop' and locale = 'en');
--   begin
--     delete from public.page_blocks where page_id = pid;
--     insert into public.page_blocks select id, page_id, type, position, is_visible, data, created_at, updated_at
--       from public.page_blocks_backup_20261105 where page_id = pid;
--     delete from public.page_blocks_backup_20261105 where page_id = pid;
--     update public.pages set draft_version = draft_version + 1, updated_at = now() where id = pid;
--   end $rb$;

create table if not exists public.page_blocks_backup_20261105 (like public.page_blocks including defaults, backed_up_at timestamptz not null default now());
create index if not exists page_blocks_backup_20261105_page_idx on public.page_blocks_backup_20261105 (page_id);
alter table public.page_blocks_backup_20261105 enable row level security;
do $pol$ begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'page_blocks_backup_20261105') then
    create policy "staff read page_blocks_backup_20261105" on public.page_blocks_backup_20261105 for select using (public.is_staff());
  end if;
end $pol$;

do $ms$
declare pid uuid := (select id from public.pages where slug = 'services/machine-shop' and locale = 'en');
begin
  if pid is null then raise notice 'machine shop page not found - skipped'; return; end if;
  if exists (select 1 from public.page_blocks_backup_20261105 where page_id = pid) then raise notice 'machine shop already converted - skipped'; return; end if;
  if not (select count(*) = 14 and coalesce(max(updated_at) = '${stamp}'::timestamptz, false) from public.page_blocks where page_id = pid) then
    raise notice 'machine shop draft changed since this migration was generated - skipped'; return;
  end if;
  insert into public.page_blocks_backup_20261105 select b.*, now() from public.page_blocks b where b.page_id = pid;
  delete from public.page_blocks where page_id = pid;
  insert into public.page_blocks (page_id, type, position, is_visible, data) values
${values};
  update public.pages set draft_version = draft_version + 1, updated_at = now() where id = pid;
end
$ms$;
`;
  fs.writeFileSync(path.join("supabase", "migrations", "0064_machine_shop_layout.sql"), sql);
  console.log("wrote 0064_machine_shop_layout.sql,", next.length, "blocks; guard stamp", stamp);
}
void main().catch((e) => { console.error(e instanceof Error ? e.message : e); process.exit(1); });
